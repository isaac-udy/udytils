package dev.isaacudy.udytils.trace.gradle

import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import org.gradle.api.DefaultTask
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.Internal
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import java.io.File

@CacheableTask
abstract class GenerateTraceSiteTableTask : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val manifests: ConfigurableFileCollection

    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val classification: RegularFileProperty

    @get:Internal
    abstract val rootDirectory: DirectoryProperty

    @get:Input
    abstract val packageName: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val root = rootDirectory.get().asFile
        val sites = manifests.files
            .flatMap { dir -> dir.walkTopDown().filter { it.extension == "json" }.toList() }
            .map { json.decodeFromString(Manifest.serializer(), it.readText()) }
        val classified = json.decodeFromString(Classification.serializer(), classification.get().asFile.readText())
        val table = SiteTable.join(sites, classified, root)
        val dir = outputDirectory.get().asFile.apply { deleteRecursively(); mkdirs() }
        File(dir, "TraceSiteTable.kt").writeText(table.render(packageName.get(), classified.constructs.map { it.id }))
    }

    private companion object {
        val json = Json { ignoreUnknownKeys = true }
    }
}

@Serializable
internal class Manifest(val file: String, val sites: List<ManifestSite>)

@Serializable
internal class ManifestSite(val siteId: Long, val name: String, val line: Int)

@Serializable
internal class Classification(val constructs: List<ClassifiedConstruct>, val declarations: List<Declaration>)

@Serializable
internal class ClassifiedConstruct(val id: String)

@Serializable
internal class Declaration(val path: String, val startLine: Int, val endLine: Int, val constructs: List<String>)

internal class SiteTable(private val constructsBySite: Map<Long, List<String>>) {
    fun render(packageName: String, constructIds: List<String>): String = buildString {
        appendLine("// Generated by generateTraceSiteTable.")
        appendLine("package $packageName")
        appendLine()
        appendLine("object TraceSiteTable : dev.isaacudy.udytils.trace.SiteTable {")
        appendLine("    override fun constructsOf(siteId: Long): List<String> = when (siteId) {")
        for ((siteId, constructs) in constructsBySite.toSortedMap()) {
            appendLine("        ${siteId}L -> listOf(${constructs.joinToString { "\"$it\"" }})")
        }
        appendLine("        else -> emptyList()")
        appendLine("    }")
        appendLine("}")
        appendLine()
        append(renderConstructs(constructIds))
    }

    companion object {
        /** Assigns each site the Constructs of the innermost classified declaration whose lines contain the site's line. */
        fun join(manifests: List<Manifest>, classification: Classification, root: File): SiteTable {
            val declarationsByPath = classification.declarations.groupBy { it.path }
            val constructs = mutableMapOf<Long, List<String>>()
            for (manifest in manifests) {
                val path = File(manifest.file).relativeToOrSelf(root).invariantSeparatorsPath
                val declarations = declarationsByPath[path].orEmpty()
                for (site in manifest.sites) {
                    val owner = declarations.filter { site.line in it.startLine..it.endLine }.minByOrNull { it.endLine - it.startLine }
                    if (owner != null && owner.constructs.isNotEmpty()) constructs[site.siteId] = owner.constructs
                }
            }
            return SiteTable(constructs)
        }

        /** `ClientData.Repository` becomes `Constructs.ClientData.Repository`. */
        fun renderConstructs(ids: List<String>): String {
            class Node(val children: MutableMap<String, Node> = sortedMapOf(), var id: String? = null)
            val root = Node()
            for (id in ids.distinct()) {
                var node = root
                id.split('.').forEach { node = node.children.getOrPut(it) { Node() } }
                node.id = id
            }
            fun StringBuilder.render(name: String, node: Node, indent: String) {
                val leaves = node.children.filterValues { it.children.isEmpty() }
                val groups = node.children.filterValues { it.children.isNotEmpty() }
                appendLine("${indent}object $name {")
                leaves.forEach { (leaf, child) -> appendLine("$indent    const val $leaf: String = \"${child.id}\"") }
                groups.forEach { (group, child) -> render(group, child, "$indent    ") }
                appendLine("$indent}")
            }
            return buildString { render("Constructs", root, "") }
        }
    }
}
